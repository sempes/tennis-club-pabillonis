-- Scadenza prenotazioni passate: conserva lo storico, cambia solo lo stato.
create or replace function public.expire_past_bookings()
returns integer language plpgsql security definer set search_path=public
as $$
declare affected integer;
begin
 update public.bookings
 set status='expired'
 where status='active' and (booking_date < current_date
   or (booking_date=current_date and end_time <= localtime));
 get diagnostics affected = row_count;
 return affected;
end $$;