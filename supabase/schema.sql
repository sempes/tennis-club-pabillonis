-- Tennis Club Pabillonis: schema iniziale Supabase
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete restrict,
  full_name text not null,
  email text not null unique,
  role text not null default 'member' check (role in ('admin','member')),
  status text not null default 'active' check (status in ('active','suspended','deleted')),
  created_at timestamptz not null default now()
);

create table if not exists public.courts (
  id bigint generated by default as identity primary key,
  name text not null unique,
  active boolean not null default true
);
insert into public.courts(id,name) values (1,'Campo 1'),(2,'Campo 2')
on conflict (id) do nothing;

create table if not exists public.bookings (
  id uuid primary key default gen_random_uuid(),
  court_id bigint not null references public.courts(id),
  booking_date date not null,
  start_time time not null,
  end_time time not null,
  booking_type text not null check (booking_type in ('singles','doubles')),
  owner_id uuid not null references public.profiles(id),
  status text not null default 'active' check (status in ('active','cancelled','expired')),
  created_at timestamptz not null default now(),
  check (end_time = start_time + interval '1 hour'),
  check (start_time >= time '00:00' and start_time < time '23:00')
);

create table if not exists public.booking_players (
  id uuid primary key default gen_random_uuid(),
  booking_id uuid not null references public.bookings(id) on delete cascade,
  member_id uuid references public.profiles(id) on delete set null,
  display_name text not null,
  created_at timestamptz not null default now()
);

-- Impedisce anche due richieste simultanee sullo stesso campo/orario.
create unique index if not exists one_active_booking_per_court_slot
on public.bookings(court_id, booking_date, start_time)
where status='active';

create index if not exists bookings_date_idx on public.bookings(booking_date,status,court_id,start_time);
create index if not exists booking_players_member_idx on public.booking_players(member_id);

-- Access helpers
create or replace function public.is_active_member()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from profiles where id=auth.uid() and status='active') $$;

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from profiles where id=auth.uid() and role='admin' and status='active') $$;

alter table public.profiles enable row level security;
alter table public.courts enable row level security;
alter table public.bookings enable row level security;
alter table public.booking_players enable row level security;

create policy "active members can read active member directory"
on public.profiles for select to authenticated
using (public.is_active_member() and status='active' or id=auth.uid() or public.is_admin());
create policy "admins manage profiles"
on public.profiles for all to authenticated
using (public.is_admin()) with check (public.is_admin());

create policy "active members read courts"
on public.courts for select to authenticated using (public.is_active_member());
create policy "admins manage courts"
on public.courts for all to authenticated using (public.is_admin()) with check (public.is_admin());

create policy "active members read bookings"
on public.bookings for select to authenticated using (public.is_active_member());
create policy "members cancel own bookings admins all"
on public.bookings for update to authenticated
using (public.is_admin() or owner_id=auth.uid()) with check (public.is_admin() or owner_id=auth.uid());

create policy "active members read booking players"
on public.booking_players for select to authenticated using (public.is_active_member());
create policy "admin manage players"
on public.booking_players for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- Atomic booking operation: checks horizon, court collision and one active booking per member.
create or replace function public.create_booking(
 p_court_id bigint, p_booking_date date, p_start_time time,
 p_booking_type text, p_players jsonb
) returns uuid language plpgsql security definer set search_path=public
as $$
declare
 v_id uuid;
 v_count int;
 v_player jsonb;
 v_member uuid;
 v_owner uuid := auth.uid();
begin
 if not public.is_active_member() then raise exception 'account_not_active'; end if;
 if p_booking_date < current_date or p_booking_date > current_date + 2 then raise exception 'booking_horizon_invalid'; end if;
 if p_start_time < time '00:00' or p_start_time >= time '23:00' then raise exception 'invalid_start_time'; end if;
 if p_booking_type not in ('singles','doubles') then raise exception 'invalid_booking_type'; end if;
 v_count := case when p_booking_type='singles' then 2 else 4 end;
 if jsonb_typeof(p_players)<>'array' or jsonb_array_length(p_players)<>v_count then raise exception 'invalid_players'; end if;
 if (select count(distinct nullif(value->>'member_id','')) from jsonb_array_elements(p_players)) <>
    (select count(*) from jsonb_array_elements(p_players) where nullif(value->>'member_id','') is not null)
 then raise exception 'duplicate_member_in_booking'; end if;
 if exists(select 1 from bookings where court_id=p_court_id and booking_date=p_booking_date and start_time=p_start_time and status='active') then raise exception 'slot_unavailable'; end if;
 -- Advisory transaction lock serializes overlapping member checks for each member ID.
 for v_player in select value from jsonb_array_elements(p_players) loop
   v_member := nullif(v_player->>'member_id','')::uuid;
   if v_member is not null then
     perform pg_advisory_xact_lock(hashtext(v_member::text));
     if not exists(select 1 from profiles where id=v_member and status='active') then raise exception 'member_not_active'; end if;
     if exists(select 1 from booking_players bp join bookings b on b.id=bp.booking_id where bp.member_id=v_member and b.status='active' and b.booking_date>=current_date) then
       raise exception 'member_already_booked';
     end if;
   elsif coalesce(trim(v_player->>'display_name'),'')='' then raise exception 'guest_name_required';
   end if;
 end loop;
 -- Owner must be included as a member in the player list.
 if not exists(select 1 from jsonb_array_elements(p_players) x where nullif(x->>'member_id','')::uuid=v_owner) then
   raise exception 'booking_owner_must_play';
 end if;
 insert into bookings(court_id,booking_date,start_time,end_time,booking_type,owner_id)
 values(p_court_id,p_booking_date,p_start_time,p_start_time+interval '1 hour',p_booking_type,v_owner)
 returning id into v_id;
 for v_player in select value from jsonb_array_elements(p_players) loop
   v_member := nullif(v_player->>'member_id','')::uuid;
   insert into booking_players(booking_id,member_id,display_name)
   values(v_id,v_member,trim(v_player->>'display_name'));
 end loop;
 return v_id;
end $$;

revoke all on function public.create_booking(bigint,date,time,text,jsonb) from public;
grant execute on function public.create_booking(bigint,date,time,text,jsonb) to authenticated;

